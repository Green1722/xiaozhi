#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
把 ask.mp3 转换为 C 头文件 ask_mp3.h
生成后放到 PhysicalExamControl.ino 同目录，Arduino 直接编译进固件。
用法：python mp3_to_header.py
"""
import os

# ask.mp3 路径（可修改）
MP3_PATH = r"C:\Users\sxc\Desktop\hight_weight\ask.mp3"
# 输出头文件（放到 .ino 同目录）
OUT_H    = os.path.join(os.path.dirname(__file__), "ask_mp3.h")

with open(MP3_PATH, "rb") as f:
    data = f.read()

lines = []
lines.append("// Auto-generated by mp3_to_header.py — DO NOT EDIT")
lines.append("#pragma once")
lines.append("#include <pgmspace.h>")
lines.append(f"static const uint32_t ASK_MP3_SIZE = {len(data)};")
lines.append("static const uint8_t ASK_MP3_DATA[] PROGMEM = {")

# 每行 16 字节
for i in range(0, len(data), 16):
    chunk = data[i:i+16]
    hex_str = ", ".join(f"0x{b:02X}" for b in chunk)
    lines.append(f"  {hex_str},")

lines.append("};")

with open(OUT_H, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"[OK] 生成 {OUT_H}  ({len(data)} 字节)")
print(f"     现在重新编译烧录 PhysicalExamControl.ino 即可。")
